def img(name, cap):
    b = base64.b64encode((IMG / name).read_bytes()).decode()
    return f'<figure><img src="data:image/png;base64,{b}" alt="{cap}"><figcaption>{cap}</figcaption></figure>'


def crit(*ks):
    return "".join(f'<span class="crit">критерий {k}</span>' for k in ks)


def table(head, rows, num=(), best=None):
    h = "".join(f'<th class="{"num" if i in num else ""}">{c}</th>' for i, c in enumerate(head))
    body = ""
    for r_i, r in enumerate(rows):
        cls = ' class="best"' if best is not None and r_i == best else ""
        body += f"<tr{cls}>" + "".join(f'<td class="{"num" if i in num else ""}">{c}</td>' for i, c in enumerate(r)) + "</tr>"
    return f"<table><thead><tr>{h}</tr></thead><tbody>{body}</tbody></table>"


def wsd(what, did, gave):
    return table(["", ""], [["<b>Что видим</b>", what], ["<b>Что сделали</b>", did], ["<b>Что дало</b>", gave]])


