"""Коэффициенты особых дней относительно обычного дня того же типа (медиана соседних 4 недель)."""
import duckdb, pandas as pd, numpy as np
L=duckdb.sql("select * from read_csv('dataset/labels/labels_day_*.csv',delim=';')").df(); L['date']=pd.to_datetime(L['date'])
D=L[L.route!=5].groupby('date').boardings.sum()
def ref(d, dow):
    c=[d+pd.Timedelta(weeks=k) for k in (-2,-1,1,2)]
    c=[x.replace() for x in c]; return np.median([D.get(x - pd.Timedelta(days=(x.dayofweek-dow)%7),np.nan) for x in c])
days={'2025-05-01 Чт праздник':('2025-05-01',6),'2025-05-02 Пт выходной-перенос':('2025-05-02',6),'2025-05-08 Чт выходной':('2025-05-08',6),
'2025-05-09 Пт праздник':('2025-05-09',6),'2025-06-12 Чт праздник':('2025-06-12',6),'2025-06-13 Пт выходной':('2025-06-13',6),
'2025-02-24 Пн? (23.02 вс)':('2025-02-24',0),'2025-03-07 Пт сокращ.':('2025-03-07',4),'2025-04-30 Ср сокращ.':('2025-04-30',2),
'2025-06-11 Ср сокращ.':('2025-06-11',2),'2025-05-03 Сб между праздн.':('2025-05-03',5),'2025-05-10 Сб между праздн.':('2025-05-10',5),'2025-06-14 Сб после праздн.':('2025-06-14',5),
'2025-01-09 Чт 1-й рабочий':('2025-01-09',3),'2025-01-10 Пт':('2025-01-10',4),'2025-01-13 Пн':('2025-01-13',0)}
for k,(d,dow) in days.items():
    d=pd.Timestamp(d); print(f'{k:32s} {D[d]:>8.0f}  ratio_vs_{"вс" if dow==6 else "свой тип"} = {D[d]/ref(d,dow):.2f}')
# школьные каникулы: 04-12.10 и 22.02-01.03 vs соседние недели (будни)
wd=D[D.index.dayofweek<5]; w=wd.groupby(wd.index.to_period('W')).mean()
print(w['2025-02-03':'2025-03-23'].round(-2).to_string()); print(w['2025-09-22':'2025-10-26'].round(-2).to_string())
