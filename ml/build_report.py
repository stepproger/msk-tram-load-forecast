def explain(name):
    what, did, gave = EXPL[name]
    rows = [[P("<b>Что видим</b>", "cell"), P(what, "cell")], [P("<b>Что сделали</b>", "cell"), P(did, "cell")],
            [P("<b>Что дало</b>", "cell"), P(gave, "cell")]]
    t = Table(rows, colWidths=[0.17 * CW, 0.83 * CW])
    t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("BACKGROUND", (0, 0), (0, -1), TINT),
                           ("LINEBELOW", (0, 0), (-1, -1), 0.4, LINE), ("TOPPADDING", (0, 0), (-1, -1), 4),
                           ("BOTTOMPADDING", (0, 0), (-1, -1), 4), ("LEFTPADDING", (0, 0), (-1, -1), 5)]))
    return [t, Spacer(1, 4 * mm)]


def img(name, width=CW, caption=None):
    path = f"docs/img/{name}"
    from PIL import Image as PI
    w, h = PI.open(path).size
    out = [Image(path, width=width, height=width * h / w)]
    if caption:
        out.append(P(caption, "cap"))
    if name in EXPL:
        return KeepTogether(out + explain(name))
    return KeepTogether(out)


def table(rows, widths, header=True, zebra=True, bold_first_col=False):
    data = [[P(str(c), "cellb" if (header and i == 0) or (bold_first_col and j == 0) else "cell")
             for j, c in enumerate(r)] for i, r in enumerate(rows)]
    t = Table(data, colWidths=[w * CW for w in widths], repeatRows=1 if header else 0)
    style = [("VALIGN", (0, 0), (-1, -1), "TOP"), ("LINEBELOW", (0, 0), (-1, -1), 0.4, LINE),
             ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
             ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5)]
    if header:
        style += [("LINEBELOW", (0, 0), (-1, 0), 1, INK2)]
    if zebra:
        style += [("BACKGROUND", (0, i), (-1, i), colors.HexColor("#f6f6f4")) for i in range(2, len(rows), 2)]
    t.setStyle(TableStyle(style))
    return t


def kpis(items):
    cells = [[P(v, "kpi_v"), P(l, "kpi_l")] for v, l in items]
    t = Table([[Table([[c[0]], [c[1]]], colWidths=[CW / len(items) - 8]) for c in cells]],
              colWidths=[CW / len(items)] * len(items))
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), TINT), ("LINEAFTER", (0, 0), (-2, -1), 3, colors.white),
                           ("TOPPADDING", (0, 0), (-1, -1), 8), ("BOTTOMPADDING", (0, 0), (-1, -1), 8)]))
    return t


def arch_diagram():
    """Схема модулей в пределах ширины страницы: 5 колонок × 3 ряда."""
    import math
    d = Drawing(CW, 170)
    bw, bh, gap = 92, 40, (CW - 5 * 92) / 4
    col = [i * (bw + gap) for i in range(5)]
    row = {"top": 118, "mid": 64, "bot": 10}
    boxes = {
        "raw": (0, "top", "Сырые валидации", "62 млн строк, 10 ГБ", "src"),
        "gtfs": (0, "mid", "Справочники GTFS", "маршруты, остановки", "src"),
        "ext": (0, "bot", "Внешние данные", "календарь, погода, сеть", "src"),
        "ing": (1, "mid", "1. Приём", "CSV → Parquet", "ml"),
        "feat": (2, "mid", "2. Признаки", "сетка, календарь", "ml"),
        "mod": (3, "top", "3. Прогноз", "уровень × форма × …", "ml"),
        "sub": (3, "bot", "Сабмит", "14 640 строк", "src"),
        "art": (4, "top", "4. Артефакты", "Parquet + JSON", "ml"),
        "be": (4, "mid", "5. Backend", "Java 21 · WebFlux", "svc"),
        "fe": (4, "bot", "6. Frontend", "React 19 · MapLibre", "svc"),
    }
    pos = {}
    for k, (c, r, t1, t2, kind) in boxes.items():
        x, y = col[c], row[r]
        pos[k] = (x, y)
        d.add(Rect(x, y, bw, bh, rx=5, ry=5, fillColor=TINT if kind == "ml" else colors.white,
                   strokeColor={"ml": ACC, "svc": ACC2, "src": LINE}[kind], strokeWidth=1))
        d.add(String(x + 6, y + 25, t1, fontName="DVB", fontSize=7.4, fillColor=INK))
        d.add(String(x + 6, y + 11, t2, fontName="DV", fontSize=6.3, fillColor=INK2))

    def arrow(a, b, sa="r", sb="l"):
        def pt(k, side):
            x, y = pos[k]
            return {"r": (x + bw, y + bh / 2), "l": (x, y + bh / 2), "t": (x + bw / 2, y + bh), "b": (x + bw / 2, y)}[side]
        (x1, y1), (x2, y2) = pt(a, sa), pt(b, sb)
        d.add(Line(x1, y1, x2, y2, strokeColor=INK2, strokeWidth=0.9))
        ang = math.atan2(y2 - y1, x2 - x1)
        d.add(Polygon([x2, y2, x2 - 6 * math.cos(ang - 0.4), y2 - 6 * math.sin(ang - 0.4),
                       x2 - 6 * math.cos(ang + 0.4), y2 - 6 * math.sin(ang + 0.4)], fillColor=INK2, strokeColor=INK2))
    arrow("raw", "ing")
    arrow("gtfs", "ing")
    arrow("ext", "feat")
    arrow("ing", "feat")
    arrow("feat", "mod")
    arrow("feat", "sub")
    arrow("mod", "art")
    arrow("art", "be", "b", "t")
    arrow("be", "fe", "b", "t")
    return d


